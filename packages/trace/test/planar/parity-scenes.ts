/**
 * Scenes whose sub-pixel and junction results are pinned against inkvec 0.2.7's own output
 * (`planar::build`, `refine_subpixel`, `refine_junctions` on the same face ids, the same f32
 * image and the same fills, shifted by ½ into Trazor's frame).
 */
import {
  diskPolygon,
  halfPlanePolygon,
  polygonScene,
  sectorsScene,
  type Rgba,
  type Scene,
} from './coverage-helpers'

export interface ParityScene {
  scene: Scene
  sigmaNoise: number
  /** Run the junction stage too (the reference is then every edge's end points). */
  junctions?: boolean
}

const INK: Rgba = [0.1, 0.12, 0.15, 1]
const PAPER: Rgba = [0.95, 0.94, 0.9, 1]
const RED: Rgba = [0.85, 0.15, 0.15, 1]
const GREEN: Rgba = [0.15, 0.75, 0.2, 1]
const BLUE: Rgba = [0.15, 0.25, 0.9, 1]

function gradientDisk(): Scene {
  const s = polygonScene(diskPolygon(8.6, 8.3, 4.2), 17, 17, INK, PAPER)
  s.gradient = [
    { x0: 0, y0: 0, x1: 17, y1: 17, c0: [0.95, 0.9, 0.55, 1], c1: [0.6, 0.85, 0.95, 1] },
    undefined,
  ]
  return s
}

