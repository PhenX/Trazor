/**
 * Inputs and reference outputs for the multimodel program tests. The inputs use
 * exact arithmetic only (`+ − × ÷` and the dyadic LCG of `fit-helpers`), so
 * inkvec rebuilds them bit for bit; the outputs are inkvec-fit 0.2.7's
 * `optimal_multimodel` (program and refinement, no post-fit passes) and
 * `segment_cost_direct` on them.
 */
import { lcg } from './fit-helpers'

type P = [number, number]

/** Rational quarter circle of radius `r`: angle 0 at `t = 0`, 90° at `t = 1`. */
function rq(r: number, t: number): P {
  const d = 1 + t * t
  return [(r * (1 - t * t)) / d, (r * (2 * t)) / d]
}

/** `pts` moved by `amp·(u − ½)` in x and y, `u` from `lcg(seed)`, interleaved. */
export function noisy(pts: P[], amp: number, seed: number): Float64Array {
  const r = lcg(seed)
  const out = new Float64Array(2 * pts.length)
  pts.forEach(([x, y], k) => {
    const nx = amp * (r() - 0.5)
    const ny = amp * (r() - 0.5)
    out[2 * k] = x + nx
    out[2 * k + 1] = y + ny
  })
  return out
}

function interleave(pts: P[]): Float64Array {
  const out = new Float64Array(2 * pts.length)
  pts.forEach(([x, y], k) => {
    out[2 * k] = x
    out[2 * k + 1] = y
  })
  return out
}

const range = (a: number, b: number) => Array.from({ length: b - a }, (_, k) => a + k)

export const lineRun = (): P[] => range(0, 40).map((k) => [k, 0.3 * k])

export const parabola = (): P[] =>
  range(0, 41).map((k) => {
    const x = 0.5 * k
    return [x, 0.02 * (x - 10) * (x - 10)]
  })

const quarter = (): P[] => range(0, 25).map((k) => rq(20, k / 24))

const ell = (): P[] => [
  ...range(0, 16).map((k): P => [k, 0]),
  ...range(1, 13).map((k): P => [15, k]),
]

const sCurve = (): P[] =>
  range(0, 41).map((k) => {
    const x = 0.5 * k
    const u = x - 10
    return [x, 0.002 * u * u * u - 0.3 * u]
  })

const ellipseArc = (): P[] =>
  range(0, 65).map((k) => {
    const t = (1.2 * k) / 64
    const d = 1 + t * t
    return [(30 * (1 - t * t)) / d, (12 * (2 * t)) / d]
  })

const zigzag = (): P[] => range(0, 40).map((k) => [k, k % 2 === 1 ? 0.8 : 0])

const staircase = (): P[] => range(0, 30).map((k) => [k, Math.floor(k / 3)])

/**
 * A rounded rectangle `w × h` with corner radius `r`, sides sampled at unit
 * spacing from `(r, 0)`, `per` samples per rational quarter circle. Each side
 * starts at a tangent point: indices `0`, `w − 2r`, `+per`, `+h − 2r`, … .
 */
export function roundedRect(w: number, h: number, r: number, per: number): P[] {
  const out: P[] = []
  const sx = w - 2 * r
  const sy = h - 2 * r
  for (let k = 0; k < sx; k++) out.push([r + k, 0])
  for (let k = 0; k < per; k++) {
    const [x, y] = rq(r, k / per)
    out.push([w - r + y, r - x])
  }
  for (let k = 0; k < sy; k++) out.push([w, r + k])
  for (let k = 0; k < per; k++) {
    const [x, y] = rq(r, k / per)
    out.push([w - r + x, h - r + y])
  }
  for (let k = 0; k < sx; k++) out.push([w - r - k, h])
  for (let k = 0; k < per; k++) {
    const [x, y] = rq(r, k / per)
    out.push([r - y, h - r + x])
  }
  for (let k = 0; k < sy; k++) out.push([0, h - r - k])
  for (let k = 0; k < per; k++) {
    const [x, y] = rq(r, k / per)
    out.push([r - x, r - y])
  }
  return out
}

/** A circle as four rational quarter circles of `per` samples each. */
export function rationalCircle(cx: number, cy: number, r: number, per: number): P[] {
  const out: P[] = []
  for (let q = 0; q < 4; q++) {
    for (let k = 0; k < per; k++) {
      const [x, y] = rq(r, k / per)
      const [u, v] = q === 0 ? [x, y] : q === 1 ? [-y, x] : q === 2 ? [-x, -y] : [y, -x]
      out.push([cx + u, cy + v])
    }
  }
  return out
}

/** A five-pointed star, 12 samples per edge; its tips are indices 0, 24, 48, 72, 96. */
export function star(): P[] {
  const v: P[] = [
    [0, -20],
    [5, -6],
    [19, -6],
    [8, 3],
    [12, 17],
    [0, 8],
    [-12, 17],
    [-8, 3],
    [-19, -6],
    [-5, -6],
  ]
  const out: P[] = []
  for (let e = 0; e < 10; e++) {
    const a = v[e]
    const b = v[(e + 1) % 10]
    for (let k = 0; k < 12; k++) {
      const t = k / 12
      out.push([a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t])
    }
  }
  return out
}

const wiggle = (): P[] =>
  range(0, 900).map((k) => {
    const x = 0.5 * k
    return [x, 3e-6 * (x - 50) * (x - 150) * (x - 350)]
  })

/** How a reference case was fitted: free, capped, or with forced vertices. */
export type Mode = 'free' | 'capped' | 'forced'

/** One reference input. */
export interface ReferenceInput {
  name: string
  points: Float64Array
  sigma: number
  closed: boolean
  lambda: number
  maxSpan: number
  forced: number[]
  mode: Mode
}

